/// The schema of a dialect.
pub fn schema(dialect: Dialect) -> &'static str {
    match dialect {
        Dialect::Sqlite => SQLITE,
        Dialect::Postgres => POSTGRES,
        Dialect::Mysql => MYSQL,
    }
}

/// An index built only when something asks for it: (name, table, columns
/// for SQLite and PostgreSQL, columns for MySQL, which indexes a prefix of
/// long text). PostgreSQL indexes a URL by its hash: a btree entry cannot
/// hold a URL of a few kilobytes.
pub struct LazyIndex {
    pub name: &'static str,
    pub table: &'static str,
    pub sqlite: &'static str,
    pub postgres: &'static str,
    pub mysql: &'static str,
}

/// For a view's per-URL lookups of issues.
pub const ISSUES_BY_URL: LazyIndex =
    LazyIndex { name: "issues_url", table: "issues", sqlite: "url_id", postgres: "url_id", mysql: "url_id" };

/// For looking up the links to or from one URL. Nothing a crawl, its
/// checks or a whole export does needs them (those read the table in one
/// pass), and on 5.7 million links they take 10 s to build: they are built
/// by whatever first asks a per-URL question.
pub const LINKS_TO: LazyIndex = LazyIndex {
    name: "links_to",
    table: "links",
    sqlite: "crawl_id, to_url",
    postgres: "crawl_id, md5(to_url)",
    mysql: "crawl_id, to_url(255)",
};
pub const LINKS_FROM: LazyIndex =
    LazyIndex { name: "links_from", table: "links", sqlite: "from_url_id", postgres: "from_url_id", mysql: "from_url_id" };

