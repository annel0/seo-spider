//! The schema, once per dialect, and the column lists the bulk writes use.
//! The tables and columns are the same everywhere; what differs is types
//! (BLOB, BYTEA, LONGBLOB), how the crawl id is generated, and which
//! indexes a database can build on long text. SQLite keeps the schema its
//! files have always had (foreign keys, a unique URL per crawl); the
//! servers rely on the crawler for both, and leave out what would only slow
//! their bulk loads.

use crate::sql::{Columns, Dialect, Kind};

pub const SQLITE: &str = r#"
PRAGMA journal_mode = WAL;
PRAGMA synchronous = NORMAL;
PRAGMA foreign_keys = ON;
PRAGMA temp_store = MEMORY;
PRAGMA cache_size = -65536;

CREATE TABLE IF NOT EXISTS crawls (
    id INTEGER PRIMARY KEY,
    start_url TEXT NOT NULL,
    started_at TEXT NOT NULL DEFAULT (datetime('now')),
    finished_at TEXT,
    config TEXT NOT NULL DEFAULT '{}',
    -- Asked to stop before its queue ran out: `continue` can take it on.
    stopped INTEGER NOT NULL DEFAULT 0
);

-- Every URL the crawl requested, redirect hops included.
CREATE TABLE IF NOT EXISTS urls (
    id INTEGER PRIMARY KEY,
    crawl_id INTEGER NOT NULL REFERENCES crawls(id),
    url TEXT NOT NULL,
    status INTEGER NOT NULL,
    location TEXT,
    content_type TEXT,
    ttfb_ms INTEGER NOT NULL DEFAULT 0,
    size INTEGER NOT NULL DEFAULT 0,
    error TEXT,
    headers TEXT NOT NULL DEFAULT '[]',
    -- Same site as the start URL (subdomains too when the crawl covers them).
    internal INTEGER NOT NULL,
    depth INTEGER,
    in_sitemap INTEGER NOT NULL DEFAULT 0,
    blocked_by_robots INTEGER NOT NULL DEFAULT 0,
    UNIQUE (crawl_id, url)
);

-- Facts read from one document of a URL: the raw body or the rendered DOM.
CREATE TABLE IF NOT EXISTS facts (
    url_id INTEGER NOT NULL REFERENCES urls(id),
    source TEXT NOT NULL,
    title TEXT,
    description TEXT,
    h1 TEXT,
    canonical TEXT,
    robots TEXT,
    word_count INTEGER NOT NULL,
    text_hash TEXT NOT NULL,
    links INTEGER NOT NULL,
    -- PageFacts as JSON, or zstd-compressed JSON (see `decode_facts`).
    data BLOB NOT NULL,
    PRIMARY KEY (url_id, source)
);

CREATE TABLE IF NOT EXISTS links (
    crawl_id INTEGER NOT NULL REFERENCES crawls(id),
    from_url_id INTEGER NOT NULL REFERENCES urls(id),
    source TEXT NOT NULL,
    to_url TEXT NOT NULL,
    anchor TEXT NOT NULL,
    rel TEXT NOT NULL,
    nofollow INTEGER NOT NULL,
    position TEXT NOT NULL,
    image INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS renders (
    url_id INTEGER PRIMARY KEY REFERENCES urls(id),
    final_url TEXT NOT NULL,
    error TEXT,
    dcl_ms INTEGER NOT NULL,
    total_ms INTEGER NOT NULL,
    settled INTEGER NOT NULL,
    load_fired INTEGER NOT NULL,
    console_errors TEXT NOT NULL,
    resources TEXT NOT NULL
);

-- Documents kept whole when the crawl dumps pages: the raw response body and
-- the rendered DOM, compressed.
CREATE TABLE IF NOT EXISTS bodies (
    url_id INTEGER NOT NULL REFERENCES urls(id),
    kind TEXT NOT NULL,
    encoding TEXT NOT NULL,
    size INTEGER NOT NULL,
    data BLOB NOT NULL,
    PRIMARY KEY (url_id, kind)
);

CREATE TABLE IF NOT EXISTS issues (
    crawl_id INTEGER NOT NULL REFERENCES crawls(id),
    url_id INTEGER NOT NULL REFERENCES urls(id),
    code TEXT NOT NULL,
    detail TEXT
);
CREATE INDEX IF NOT EXISTS issues_code ON issues (crawl_id, code);

-- The link graph between the crawl's URLs, written after its checks: per
-- target, the pages that link or redirect to it, packed (see graph.rs);
-- anchors stay in the source pages' facts.
CREATE TABLE IF NOT EXISTS inlinks (
    crawl_id INTEGER NOT NULL,
    to_id INTEGER NOT NULL,
    sources INTEGER NOT NULL,
    data BLOB NOT NULL
);
CREATE INDEX IF NOT EXISTS inlinks_to ON inlinks (crawl_id, to_id);
-- The site's template: text blocks met on many of the crawl's pages, by
-- block hash (seo_page::block_hash), with how many pages had each.
CREATE TABLE IF NOT EXISTS template_blocks (
    crawl_id INTEGER NOT NULL,
    hash INTEGER NOT NULL,
    pages INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS template_blocks_crawl ON template_blocks (crawl_id);
"#;

